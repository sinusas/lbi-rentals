#!/usr/bin/env python3
"""Fetch real walking routes (OSM foot router) between houses in each group and
from every house to every point of interest, and bake them into index.html
between the ROUTES:BEGIN / ROUTES:END markers.

Rerun after adding or moving a house or POI:  python3 build_routes.py
"""
import json, re, time, urllib.request, itertools, pathlib

HTML = pathlib.Path(__file__).with_name("index.html")
FOOT = "https://routing.openstreetmap.de/routed-foot/route/v1/driving/"
CAR = "https://routing.openstreetmap.de/routed-car/route/v1/driving/"
BIKE = "https://routing.openstreetmap.de/routed-bike/route/v1/driving/"
UA = {"User-Agent": "lbi-rentals-map/1.0"}

src = HTML.read_text()

def places(block_name):
    block = re.search(rf"const {block_name} = \[(.*?)\n\];", src, re.S).group(1)
    out = []
    for m in re.finditer(r'id: "([^"]+)".*?(?:option: "([A-Z])".*?)?lat: ([\d.-]+), lng: ([\d.-]+)', block, re.S):
        line_end = block.find("\n", m.start())
        only = re.search(r'for: "([A-Z])"', block[m.start():line_end])
        out.append({"id": m[1], "opt": m[2], "for": only and only[1], "lat": float(m[3]), "lng": float(m[4])})
    return out

houses, pois = places("HOUSES"), places("POIS")

def route(base, a, b):
    url = f"{base}{a['lng']},{a['lat']};{b['lng']},{b['lat']}?overview=full&geometries=geojson"
    for attempt in range(3):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=30) as r:
                d = json.load(r)
            break
        except Exception:
            time.sleep(3)
    else:
        raise SystemExit(f"routing failed for {a['id']} -> {b['id']}")
    time.sleep(1)  # be polite to the free FOSSGIS server
    rt = d["routes"][0]
    return rt["distance"], rt["duration"], [[round(y, 6), round(x, 6)] for x, y in rt["geometry"]["coordinates"]]

pairs = []
for opt in sorted({h["opt"] for h in houses}):
    pairs += itertools.combinations([h for h in houses if h["opt"] == opt], 2)
pairs += [(h, p) for h in houses for p in pois if not p["for"] or p["for"] == h["opt"]]

routes = {}
for a, b in pairs:
    dist, dur, geom = route(FOOT, a, b)
    entry = {"m": round(dist), "min": max(1, round(dur / 60)), "path": geom}
    bd, bt, _ = route(BIKE, a, b)
    entry["bike"] = {"m": round(bd), "min": max(1, round(bt / 60))}
    if dist > 2000:  # long trips (e.g. Holgate to town): also give a driving time
        cd, ct, _ = route(CAR, a, b)
        entry["drive"] = {"m": round(cd), "min": max(1, round(ct / 60))}
    routes[f"{a['id']}|{b['id']}"] = entry
    print(f"{a['id']:>6} -> {b['id']:<6} {dist:6.0f} m  {entry['min']:3d} min walk {entry['bike']['min']:3d} min bike" + (f"  ({entry['drive']['min']} min drive)" if "drive" in entry else ""))

block = "// ROUTES:BEGIN (generated by build_routes.py; do not edit by hand)\nconst ROUTES = " + json.dumps(routes, separators=(",", ":")) + ";\n// ROUTES:END"
if "// ROUTES:BEGIN" in src:
    src = re.sub(r"// ROUTES:BEGIN.*?// ROUTES:END", lambda _: block, src, flags=re.S)
else:
    src = src.replace("const byId =", block + "\n\nconst byId =", 1)
HTML.write_text(src)
print(f"wrote {len(routes)} routes into {HTML.name}")
